"""Research cases computed from the public teaching store."""
from public_study import kes_case, record, slot


def fixture(sample, name, question, evidence, mechanism, steps):
    rows = [record(i, kind, title, text, f"Учебный набор · {name} · {i}", roles)
            for i, kind, title, text, roles in evidence]
    backlog = [record(row["id"], "Задача", row["title"], row["text"], row["source"],
                      mechanism=row["mechanism"], version=row["version"], address=row["record"])
               for row in sample["tasks"] if row.get("product") == name]
    return {"question": question, "rows": rows + backlog, "mechanism": mechanism, "steps": steps}


